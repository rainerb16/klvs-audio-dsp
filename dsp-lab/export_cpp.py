"""Generate plugins/WRM1/Source/AutoGainTable.h from autogain_table.json.

Run after every calibrate.py:   python export_cpp.py
The C++ plugin never contains hand-copied numbers from the Python model.
"""
import json
from pathlib import Path

import wrm1

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "plugins/WRM1/Source/AutoGainTable.h"


def fmt(v):
    return f"{v:.3f}"


def main():
    t = json.loads(wrm1.AUTOGAIN_TABLE_PATH.read_text())
    grid = t["drive_grid_db"]
    step = grid[1] - grid[0]
    assert all(b - a == step for a, b in zip(grid, grid[1:])), "drive grid must be uniform"
    assert t["low_protect_grid"] == [0.0, 0.5, 1.0]
    # Engine.cpp hard-codes drive = min + (max - min) * warmth: keep the taper linear or update it.
    assert wrm1.WARMTH_TAPER == 1.0, "Engine.cpp assumes a linear Warmth taper"
    names = list(wrm1.CHARACTERS)  # order = Character parameter index
    assert names == ["tape", "tube", "console"]

    rows = []
    for name in names:
        c = t["characters"][name]
        comp = ",\n          ".join("{ " + ", ".join(fmt(v) for v in r) + " }" for r in c["drive_comp_db"])
        rows.append(f"    // {name}\n    {{ {{ {comp} }},\n      {fmt(c['body_db_per_unit'])}, "
                    f"{fmt(c['tone_db_pos'])}, {fmt(c['tone_db_neg'])} }}")

    OUT.write_text(f"""// GENERATED by dsp-lab/export_cpp.py from dsp-lab/autogain_table.json. Do not edit by hand.
// Reference: {t['reference']}
#pragma once

namespace wrm1::autogain
{{
inline constexpr double driveGridStartDb = {grid[0]:.1f};
inline constexpr double driveGridStepDb = {step:.1f};
inline constexpr int driveGridSize = {len(grid)};
inline constexpr double lowProtectGrid[3] = {{ 0.0, 0.5, 1.0 }};

struct CharacterTable
{{
    double driveCompDb[3][driveGridSize]; // [lowProtect row][drive]
    double bodyDbPerUnit;
    double toneDbPos;
    double toneDbNeg;
}};

// Index = Character parameter (0 Tape, 1 Tube, 2 Console)
inline constexpr CharacterTable tables[3] = {{
{(','+chr(10)).join(rows)}
}};
}} // namespace wrm1::autogain
""")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
